create or replace function public.increment_linkr_terminal_message_count(
  p_conversation_id uuid,
  p_user_id uuid,
  p_delta integer,
  p_preview text default null,
  p_role text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if p_delta < 0 or p_delta > 2 then
    raise exception 'invalid_message_count_delta';
  end if;

  update public.linkr_terminal_conversations
  set
    message_count = message_count + p_delta,
    last_message_preview = coalesce(left(p_preview, 180), last_message_preview),
    last_message_role = coalesce(p_role, last_message_role),
    last_message_at = case when p_preview is null then last_message_at else now() end
  where id = p_conversation_id
    and user_id = p_user_id
    and deleted_at is null
  returning message_count into v_count;

  if v_count is null then
    raise exception 'conversation_not_found';
  end if;
  return v_count;
end;
$$;

revoke all on function public.increment_linkr_terminal_message_count(uuid, uuid, integer, text, text)
  from public, anon, authenticated;
grant execute on function public.increment_linkr_terminal_message_count(uuid, uuid, integer, text, text)
  to service_role;

create or replace function public.search_linkr_user_memory(
  p_user_id uuid,
  p_query text,
  p_limit integer default 6
)
returns table (
  source_type text,
  source_id text,
  title text,
  searchable_text text,
  metadata jsonb,
  created_at timestamptz,
  rank real
)
language sql
stable
security definer
set search_path = public
as $$
  select
    umi.source_type,
    umi.source_id,
    umi.title,
    umi.searchable_text,
    umi.metadata,
    umi.created_at,
    ts_rank_cd(
      to_tsvector('english', umi.searchable_text),
      websearch_to_tsquery('english', left(coalesce(p_query, ''), 200))
    )::real as rank
  from public.user_memory_index umi
  where umi.user_id = p_user_id
    and nullif(btrim(coalesce(p_query, '')), '') is not null
    and to_tsvector('english', umi.searchable_text)
      @@ websearch_to_tsquery('english', left(coalesce(p_query, ''), 200))
  order by rank desc, umi.created_at desc
  limit least(greatest(coalesce(p_limit, 6), 1), 20);
$$;

revoke all on function public.search_linkr_user_memory(uuid, text, integer)
  from public, anon, authenticated;
grant execute on function public.search_linkr_user_memory(uuid, text, integer)
  to service_role;
